            // Uses a bundled debug-style keystore for reproducible release builds in CI.
            // Replace with a real keystore for production distribution.
            val keystorePath = file("keystore/taskflow-release.jks")
            if (keystorePath.exists()) {
                val props = Properties().apply { load(file("keystore/keystore.properties").inputStream()) }
                storeFile = keystorePath
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            } else {
                // Fallback to debug signing so release variant always builds.
                storeFile = file("${System.getProperty("user.home")}/.android/debug.keystore")
                storePassword = "android"
                keyAlias = "androiddebugkey"
                keyPassword = "android"
            }
        }
    }

